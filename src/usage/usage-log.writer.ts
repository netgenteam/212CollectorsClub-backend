import { Injectable, Logger } from '@nestjs/common';
import type { OnModuleDestroy } from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import pg from 'pg';
import type { UsageLogRow, UsageLogWriter } from './usage-log.types.js';

/** The database cuts the INSERT itself if it runs longer: no statement outlives the buffer's own timer. */
const STATEMENT_TIMEOUT_MS = 4_000;
const LOCK_TIMEOUT_MS = 1_000;
/** Closing the writer's connection must not wait for a database that does not answer. */
const POOL_END_TIMEOUT_MS = 2_000;

/**
 * Story 20.7: ONE `INSERT ... SELECT` per batch (not `createMany`: it cannot carry the `WHERE`, and it would
 * send 200 x 10 bound parameters). Things it does that `createMany` cannot:
 *
 *   - a row of a CUSTOMER whose account is already anonymized is not inserted (`NOT EXISTS ... anonymizedAt IS NOT NULL`):
 *     the in-memory buffer can hold a row that was queued before the anonymization committed, and this
 *     is what keeps it from coming back (the other half is `UsageLogErasure`, docs/deployment.md 19.5);
 *   - `ON CONFLICT ("requestId") DO NOTHING` (Story 20.7 round 2): the writer is idempotent. When a `COMMIT`
 *     expired on the client side but had committed on the server, the buffer re-queued the batch and the
 *     rows were written twice (20 requests, 40 rows). The request id is generated by the server per request
 *     (a client's `X-Request-Id` is ignored), so one id is one request and a repeated one is a retry.
 *
 * The batch travels as ONE jsonb parameter (`jsonb_to_recordset`), not as ten arrays: node-postgres turns an
 * array into text element by element in JavaScript (the profile showed `escapeElement`), while
 * `JSON.stringify` is native code. The statement is a literal (no string building) and the only value is
 * bound.
 */
const INSERT_SQL = `
  INSERT INTO "Usage_Logs"
    ("ts", "method", "route", "status", "durationMs", "actorType", "actorId", "ip", "userAgent", "requestId")
  SELECT to_timestamp(t."ts" / 1000.0), t."method", t."route", t."status", t."durationMs", t."actorType",
         t."actorId", t."ip", t."userAgent", t."requestId"
    FROM jsonb_to_recordset($1::jsonb) AS t(
      "ts" bigint, "method" text, "route" text, "status" smallint, "durationMs" int,
      "actorType" text, "actorId" uuid, "ip" inet, "userAgent" text, "requestId" uuid)
   WHERE t."actorType" <> 'CUSTOMER'
      OR t."actorId" IS NULL
      OR NOT EXISTS (
           SELECT 1 FROM "Customers" c
            WHERE c."id" = t."actorId" AND c."anonymizedAt" IS NOT NULL)
  ON CONFLICT ("requestId") DO NOTHING`;

@Injectable()
export class PrismaUsageLogWriter implements UsageLogWriter, OnModuleDestroy {
  private readonly logger = new Logger(PrismaUsageLogWriter.name);
  private pool: pg.Pool | null = null;

  constructor(private readonly config: ConfigService) {}

  /**
   * Its OWN connection (one, `max: 1`), not the application's Prisma pool of 10: the writes of the log
   * never queue behind (or in front of) a customer's request for a pooled connection, `GET /categories` and
   * the INSERT do not compete for the same ten, and the write is ONE statement in autocommit (one round
   * trip instead of Prisma's `BEGIN`, `set_config`, `INSERT`, `COMMIT`). `statement_timeout` and
   * `lock_timeout` are startup parameters of the connection. Created on the first write, closed in
   * `onModuleDestroy` (after the buffer's own, which flushes first).
   */
  private getPool(): pg.Pool {
    if (this.pool) return this.pool;
    const url = new URL(this.config.getOrThrow<string>('DATABASE_URL'));
    // Prisma's `?schema=` is not a libpq parameter: it becomes the search path, as the Prisma adapter does.
    const schema = url.searchParams.get('schema');
    url.searchParams.delete('schema');
    const safeSchema =
      schema !== null && /^[A-Za-z0-9_]{1,63}$/.test(schema) ? schema : null;
    const pool = new pg.Pool({
      connectionString: url.toString(),
      max: 1,
      idleTimeoutMillis: 30_000,
      connectionTimeoutMillis: 2_000,
      query_timeout: STATEMENT_TIMEOUT_MS + 2_000,
      // startup parameters of the connection (no extra query, so no queueing behind the first INSERT)
      statement_timeout: STATEMENT_TIMEOUT_MS,
      lock_timeout: LOCK_TIMEOUT_MS,
      ...(safeSchema !== null
        ? { options: `-c search_path=${safeSchema}` }
        : {}),
    });
    // An error on an IDLE connection (the database restarted) is an event, not an exception: without a
    // listener it would end the process.
    pool.on('error', (err) => {
      this.logger.warn(`usage log connection error: ${err.message}`);
    });
    this.pool = pool;
    return pool;
  }

  async insert(rows: readonly UsageLogRow[]): Promise<void> {
    if (rows.length === 0) return;
    await this.getPool().query(INSERT_SQL, [JSON.stringify(rows)]);
  }

  async onModuleDestroy(): Promise<void> {
    const pool = this.pool;
    this.pool = null;
    if (!pool) return;
    let stop: NodeJS.Timeout | undefined;
    try {
      await Promise.race([
        pool.end(),
        new Promise<void>((resolve) => {
          stop = setTimeout(resolve, POOL_END_TIMEOUT_MS);
        }),
      ]);
    } catch {
      /* closing: nothing to tell */
    } finally {
      clearTimeout(stop);
    }
  }
}
