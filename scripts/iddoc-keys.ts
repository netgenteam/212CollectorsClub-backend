// pnpm iddoc:keys [--file <path>]   (Story 20.3; for a LOCAL development .env only)
//
// Appends the three ID-document key lines (IDDOC_ENC_KEYS, IDDOC_ENC_ACTIVE_KEY, IDDOC_BLIND_KEY) to
// the local .env when they are missing, with freshly generated keys.
//   - Idempotent: a second run changes nothing.
//   - Never overwrites or edits an existing line (only appends missing ones).
//   - Never prints a key or any value of the file: it prints variable names and "added"/"kept".
//   - Refuses to run in production (NODE_ENV=production, a target under /opt/212cc, or a target
//     file that declares NODE_ENV=production). Production keys are generated by hand and kept in
//     a secrets manager (docs/deployment.md section 14); this helper is not for servers.
// Back up the generated keys: losing IDDOC_ENC_KEYS makes the stored cedulas unrecoverable.
import { randomBytes } from 'node:crypto';
import {
  appendFileSync,
  existsSync,
  readFileSync,
  writeFileSync,
} from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import {
  ACTIVE_KEY_VAR,
  BLIND_KEY_VAR,
  ENC_KEYS_VAR,
  IdDocConfigError,
  parseIdDocKeyring,
} from '../src/crypto/id-doc-keyring.js';

export interface KeysResult {
  added: string[];
  kept: string[];
  /** Variables that exist but whose final keyring is invalid (names only, never values). */
  problems: string[];
}

const lineOf = (text: string, name: string): string | null => {
  const m = new RegExp(`^\\s*(?:export\\s+)?${name}\\s*=(.*)$`, 'm').exec(text);
  return m ? m[1].trim().replace(/^["']|["']$/g, '') : null;
};

export class KeysRefused extends Error {}

/** Throws `KeysRefused` when the target looks like a server. */
export function assertLocalOnly(
  path: string,
  text: string,
  env: NodeJS.ProcessEnv,
): void {
  if ((env.NODE_ENV ?? '').toLowerCase() === 'production') {
    throw new KeysRefused(
      'NODE_ENV=production: this helper never runs in production',
    );
  }
  if (/^\/opt\/212cc(\/|$)/.test(resolve(path))) {
    throw new KeysRefused(
      'the target is under /opt/212cc (a server): this helper never runs there',
    );
  }
  if (/^\s*NODE_ENV\s*=\s*["']?production["']?\s*$/im.test(text)) {
    throw new KeysRefused('the target file declares NODE_ENV=production');
  }
}

export function ensureIdDocKeys(
  path: string,
  env: NodeJS.ProcessEnv = process.env,
): KeysResult {
  const exists = existsSync(path);
  const text = exists ? readFileSync(path, 'utf8') : '';
  assertLocalOnly(path, text, env);
  const b64 = (): string => randomBytes(32).toString('base64');
  const has = (n: string): boolean => (lineOf(text, n) ?? '') !== '';
  const result: KeysResult = { added: [], kept: [], problems: [] };
  const toAdd: string[] = [];
  let encKeys = lineOf(text, ENC_KEYS_VAR) ?? '';
  let active = lineOf(text, ACTIVE_KEY_VAR) ?? '';
  let blind = lineOf(text, BLIND_KEY_VAR) ?? '';

  if (has(ENC_KEYS_VAR)) result.kept.push(ENC_KEYS_VAR);
  else {
    encKeys = `1:${b64()}`;
    toAdd.push(`${ENC_KEYS_VAR}=${encKeys}`);
    result.added.push(ENC_KEYS_VAR);
  }
  if (has(ACTIVE_KEY_VAR)) result.kept.push(ACTIVE_KEY_VAR);
  else {
    const versions = [...encKeys.matchAll(/(?:^|,)\s*(\d+)\s*:/g)].map((m) =>
      Number(m[1]),
    );
    active = String(versions.length > 0 ? Math.max(...versions) : 1);
    toAdd.push(`${ACTIVE_KEY_VAR}=${active}`);
    result.added.push(ACTIVE_KEY_VAR);
  }
  if (has(BLIND_KEY_VAR)) result.kept.push(BLIND_KEY_VAR);
  else {
    blind = b64();
    toAdd.push(`${BLIND_KEY_VAR}=${blind}`);
    result.added.push(BLIND_KEY_VAR);
  }

  if (toAdd.length > 0) {
    const header =
      '# ID document keys (Story 20.3, pnpm iddoc:keys). BACK THEM UP: without IDDOC_ENC_KEYS the stored cedulas cannot be recovered.\n';
    const lead = text === '' || text.endsWith('\n') ? '' : '\n';
    const block = `${lead}${header}${toAdd.join('\n')}\n`;
    if (exists) appendFileSync(path, block);
    else writeFileSync(path, block, { mode: 0o600 });
  }

  try {
    parseIdDocKeyring({ encKeys, activeKey: active, blindKey: blind });
  } catch (err) {
    if (err instanceof IdDocConfigError) result.problems = err.problems;
    else throw err;
  }
  return result;
}

function main(): number {
  const i = process.argv.indexOf('--file');
  const path = resolve(
    i >= 0 && process.argv[i + 1] ? process.argv[i + 1] : '.env',
  );
  try {
    const r = ensureIdDocKeys(path);
    for (const n of r.added)
      console.log(`[iddoc:keys] ${n}: added (value not shown)`);
    for (const n of r.kept)
      console.log(`[iddoc:keys] ${n}: already set, left untouched`);
    if (r.problems.length > 0) {
      console.error(
        '[iddoc:keys] the existing values do not form a valid keyring (fix them by hand; nothing existing was changed):',
      );
      for (const p of r.problems) console.error(`  - ${p}`);
      return 1;
    }
    if (r.added.length > 0)
      console.log(
        '[iddoc:keys] done. Back the keys up now (docs/deployment.md section 14.2).',
      );
    else console.log('[iddoc:keys] nothing to do.');
    return 0;
  } catch (err) {
    if (err instanceof KeysRefused) {
      console.error(`[iddoc:keys] refused: ${err.message}`);
      return 2;
    }
    throw err;
  }
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  process.exitCode = main();
}
